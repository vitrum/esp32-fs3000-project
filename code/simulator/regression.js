// Open index.html?test=1 to run the browser-only regression suite.
(() => {
  "use strict";
  if (!new URLSearchParams(location.search).has("test")) return;
  const sim = window.aeroProbeSim;
  const $ = (id) => document.getElementById(id);
  const results = [];
  const assert = (condition, message) => {
    if (!condition) throw new Error(message);
    results.push(message);
  };
  const change = (id, value) => {
    const input = $(id);
    if (input.type === "checkbox") input.checked = value;
    else input.value = value;
    input.dispatchEvent(new Event("change", { bubbles: true }));
  };
  const dismiss = () => $("notice-dismiss").click();
  const snapshot = () => sim.snapshot();
  const output = document.createElement("pre");
  output.id = "test-results";
  output.style.cssText = "white-space:pre-wrap;padding:20px;border:1px solid #37536b";
  document.querySelector("main").append(output);
  const originalAnchorClick = HTMLAnchorElement.prototype.click;
  const originalVolume = localStorage.getItem("aero-volume");
  const downloads = [];
  HTMLAnchorElement.prototype.click = function () { downloads.push(this.download); };
  try {
    assert(snapshot().language === "en" && snapshot().powerSrc === 0 && !snapshot().recording, "Default: English, AUTO/no source, recording off");
    $("boot-key").click();
    assert(snapshot().page === "settings-dialog" && document.querySelectorAll(".settings-grid button").length === 6, "BOOT opens all six settings entries");
    $("settings-language").click();
    $("language-zh").click();
    assert(snapshot().language === "en" && snapshot().error.includes("disabled"), "Chinese selection stays disabled like firmware");
    dismiss();
    $("language-page").querySelector("[data-back]").click();
    $("settings-back").click();
    assert(snapshot().page === "settings-dialog", "A repeated back click cannot pass through the child page into SETTINGS");
    sim.step(1);
    $("settings-back").click();
    assert(snapshot().page === "dashboard", "A new back gesture works after the navigation guard expires");
    $("boot-key").click();
    $("settings-sound").click();
    const volumeSlider = $("sound-volume-input");
    for (const volume of [0, 100, 63]) {
      volumeSlider.value = String(volume);
      volumeSlider.dispatchEvent(new Event("input", { bubbles: true }));
      assert(snapshot().volume === volume && $("sound-volume").textContent === `Volume: ${volume}%`, `Volume slider updates live at ${volume}%`);
    }
    volumeSlider.dispatchEvent(new Event("change", { bubbles: true }));
    assert(localStorage.getItem("aero-volume") === "63", "Volume slider saves an arbitrary percentage after release");
    sim.step(1);
    $("sound-page").querySelector("[data-back]").click();
    $("settings-meter").click();
    assert(document.querySelectorAll(".dialog-list .device-option").length === 3, "Power source menu has BLE, VIRTUAL and AUTO only");
    $("scan-again").click();
    sim.step(1);
    $("loading-back").click();
    assert($("loading-back").disabled, "BLE cancellation waits for release");
    sim.step(1);
    assert(snapshot().operation === null && $("ble-device-list").children.length === 0, "Cancelled scan does not fabricate results");
    $("ble-scan-again").click();
    sim.step(5);
    assert(snapshot().operation === "scan", "BLE scan remains active before six seconds");
    sim.step(1);
    assert(snapshot().page === "ble-devices-page" && $("ble-device-list").children.length === 3, "BLE scan finds CPS, FTMS and CSC demo devices");
    $("ble-device-list").children[1].click();
    assert($("confirm-device-details").textContent.includes("FTMS") && !snapshot().bleConnected, "FTMS requires explicit connection confirmation");
    $("confirm-connect").click();
    sim.step(1);
    assert(snapshot().bleConnected && snapshot().powerSrc === 1 && snapshot().page === "dashboard", "FTMS connection completes on dashboard");
    sim.openMeterDialog();
    $("scan-again").click();
    sim.step(6);
    $("ble-device-list").children[2].click();
    $("confirm-connect").click();
    sim.step(1);
    assert($("loading-title").textContent === "CONNECTION FAILED" && $("loading-message").textContent.includes("not power"), "CSC-only device reports missing power support");
    $("loading-back").click();
    change("ble-result", "failure");
    $("ble-device-list").firstElementChild.click();
    $("confirm-connect").click();
    sim.step(1);
    assert($("loading-message").textContent.includes("GATT discovery failed"), "Injected BLE connection failure reports an explicit error");
    $("loading-back").click();
    change("ble-result", "empty");
    $("ble-scan-again").click();
    sim.step(6);
    assert($("ble-device-list").children.length === 0, "Empty scan leaves no stale device rows");
    change("ble-result", "success");
    sim.openMeterDialog();
    $("virtual-source").click();
    sim.setInput({ virtualPower: 300, virtualCadence: 90, power: 100, wind: 36 });
    sim.reset();
    sim.step(3);
    assert(snapshot().power === 300 && snapshot().powerSrc === 3 && snapshot().average3 === 300, "Virtual power/cadence use separate inputs and source ID 3");
    const expected = (300 * .975 - 85 * 9.80665 * .004 * 10) / (.5 * 1.225 * 1000);
    assert(Math.abs(snapshot().cda - expected) < 1e-10, "CdA matches firmware mass, rolling resistance and efficiency formula");
    sim.setInput({ virtualPower: 600 });
    assert(snapshot().power === 600 && snapshot().average3 === 300, "Instantaneous power does not bypass 3-second CdA history");
    sim.step(1);
    assert(snapshot().average3 === 400, "Three-second CdA power history rolls correctly");
    sim.setInput({ wind: 10.7 });
    assert(snapshot().cda === null, "CdA is unavailable below 3 m/s");
    sim.setInput({ wind: 36 });
    change("wind-valid", false);
    assert($("wind-reading").textContent === "-- km/h", "Invalid wind data displays placeholder");
    change("wind-valid", true);
    $("virtual-back").click();
    $("auto-source").click();
    assert(snapshot().mode === 0 && snapshot().power === 100 && snapshot().powerSrc === 1, "AUTO uses connected BLE without ANT or virtual leakage");
    $("toggle-run").click();
    assert(!snapshot().recording && $("log-status").textContent === "LOG OFF", "Automatic sampling is independent from CSV recording");
    $("toggle-run").click();
    $("record-start").click();
    assert(snapshot().error.includes("Wi-Fi"), "Web recording command rejects disconnected Wi-Fi");
    dismiss();
    $("boot-key").click(); $("settings-wifi").click();
    assert(!$("wifi-page").querySelector('input[type="checkbox"], input[type="radio"]') && $("wifi-off").getAttribute("aria-pressed") === "true", "Wi-Fi uses OFF/ON buttons, not checkbox or radio controls");
    $("wifi-on").click();
    assert(snapshot().wifi === "provisioning", "Wi-Fi without credentials waits for SmartConfig");
    change("wifi-input", "disconnected");
    assert(snapshot().wifi === "connecting", "Unavailable access point leaves Wi-Fi connecting");
    change("wifi-input", "connected");
    sim.step(1);
    assert(snapshot().wifi === "connected" && $("wifi-status").textContent.includes("aeroprobe.local"), "Wi-Fi ON button models station connection and URLs");
    assert($("wifi-on").getAttribute("aria-pressed") === "true" && $("wifi-off").getAttribute("aria-pressed") === "false", "Wi-Fi buttons show only the active selection");
    $("wifi-off").click();
    assert(snapshot().wifi === "off" && $("wifi-off").classList.contains("selected"), "Wi-Fi OFF button disables the station and updates selection");
    $("wifi-on").click(); sim.step(1);
    change("gps-input", "fixed");
    sim.recording(true);
    sim.step(2);
    assert(snapshot().recording && snapshot().buffered === 2 && snapshot().written === 0, "CSV samples buffer in memory, not flushed every second");
    assert(snapshot().recordPath.startsWith("/LOG/2026-10-19/"), "Fresh GPS selects local-date record directory");
    change("gps-input", "stale");
    $("ble-speed-input").value = "18";
    $("ble-speed-input").dispatchEvent(new Event("input"));
    sim.step(1);
    sim.recording(false);
    let rows = snapshot().csv.trim().split("\n");
    assert(rows[0] === "t_ms,powerW,cadenceRpm,speedMps,vAirMps,yawDeg,postureDeg,rhoKgM3,powerSrc" && rows.length === 4, "CSV stop flushes all rows with exact firmware header");
    assert(Number(rows[1].split(",")[3]) > 8 && Number(rows[3].split(",")[3]) === 5, "Fresh GPS speed enters logs; stale fix falls back to BLE speed");
    assert(rows.slice(1).every((row) => row.split(",").length === 9 && row.endsWith(",1")), "CSV emits nine fields and BLE source ID 1");
    sim.recording(true); sim.step(60);
    assert(snapshot().written === 60 && snapshot().buffered === 0, "CSV flushes a complete 60-sample batch");
    if (snapshot().operation) sim.step(2);
    const bufferedBeforeAudio = snapshot().buffered;
    sim.browse("/music");
    $("sd-files").firstElementChild.click();
    assert(snapshot().audio === "/music/demo.mp3" && !snapshot().bleConnected && snapshot().powerSrc === 0, "Audio playback suspends BLE and uses simulated SD file");
    sim.step(61);
    assert(snapshot().buffered === 60 && snapshot().dropped === bufferedBeforeAudio + 1, "Audio pauses CSV submissions and reports bounded-buffer overflow");
    $("sd-stop").click();
    sim.step(1);
    assert(snapshot().audio === null && snapshot().written >= 120, "Stopping audio resumes queued CSV writes without reconnecting BLE power meter");
    sim.recording(false);
    const csvBeforeDownload = snapshot().csv;
    sim.download(); sim.download();
    assert(snapshot().downloading && snapshot().error.includes("Another download"), "Second concurrent download is rejected");
    dismiss();
    change("sd-busy", true);
    sim.step(1);
    assert(snapshot().downloading, "Download waits rather than returning EOF when SD is busy");
    sim.step(5);
    assert(!snapshot().downloading && snapshot().downloadMessage.includes("timeout"), "Download fails explicitly after five seconds of SD contention");
    change("sd-busy", false);
    sim.download();
    const blockCount = Math.ceil(csvBeforeDownload.length / 1024);
    sim.step(blockCount);
    assert(!snapshot().downloading && downloads.length === 1, "Chunked CSV download completes and offers one file");
    sim.browse("/");
    $("sd-files").lastElementChild.click();
    assert(snapshot().error === "Not an audio file", "SD browser does not play non-audio files");
    dismiss();
    change("sd-ready", false);
    sim.browse("/");
    assert($("sd-files").children.length === 0 && $("sd-status").textContent.includes("not ready"), "Unmounted SD has no fabricated file list");
    change("gps-input", "absent"); sim.step(3);
    $("boot-key").click(); $("settings-gps").click();
    assert(snapshot().error.includes("not found"), "Missing GPS produces wiring/power notice");
    dismiss();
    change("gps-input", "fixed");
    $("settings-gps").click();
    assert($("gps-data").textContent.includes("UTC") && $("gps-data").textContent.includes("LOCAL"), "GPS detail page shows UTC and UTC+8 plus fix data");
    $("gps-restart").click();
    assert(snapshot().gps === "restarting", "GPS restart begins fresh detection");
    sim.step(3);
    assert(snapshot().gps === "searching", "GPS restart returns to searching, not a fabricated immediate fix");
    change("sd-ready", true);
    sim.recording(true);
    assert(snapshot().recordPath.startsWith("/LOG/2026-10-19/"), "GPS restart retains the last known log date");
    sim.recording(false);
    for (const [entry, back] of [
      ["settings-language", "#language-page [data-back]"],
      ["settings-wifi", "#wifi-page [data-back]"],
      ["settings-sound", "#sound-page [data-back]"],
      ["settings-gps", "#gps-page [data-back]"],
      ["settings-sd", "#sd-page [data-back]"],
      ["settings-meter", "#dialog-close"]
    ]) {
      sim.step(1);
      $("boot-key").click();
      $(entry).click();
      document.querySelector(back).click();
      $("settings-back").click();
      assert(snapshot().page === "settings-dialog", `${entry}: repeated BACK stays in SETTINGS`);
      sim.step(1);
      $("settings-back").click();
      assert(snapshot().page === "dashboard", `${entry}: a fresh BACK reaches the dashboard`);
    }
    assert(document.querySelectorAll('[data-source="ANT+"], #connect-ant').length === 0, "No ANT entry remains");
    window.simulatorTestResult = { passed: results.length, failures: [], checks: results };
    output.textContent = `PASS: ${results.length} checks\n` + results.join("\n");
  } catch (error) {
    window.simulatorTestResult = { passed: results.length, failures: [error.message], checks: results };
    output.textContent = `FAIL after ${results.length} checks: ${error.stack}`;
    console.error(error);
  } finally {
    HTMLAnchorElement.prototype.click = originalAnchorClick;
    if (originalVolume === null) localStorage.removeItem("aero-volume");
    else localStorage.setItem("aero-volume", originalVolume);
  }
})();
